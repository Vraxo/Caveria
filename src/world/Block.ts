export type BlockRenderShape = 'cube' | 'torch' | 'cross';
export type ToolCategory = 'none' | 'pickaxe' | 'axe' | 'shovel';

export interface BlockDefinition {
  id: BlockId;
  name: string;
  /** Blocks player movement AABB */
  solid: boolean;
  /** Raycast can target this block */
  targetable: boolean;
  /** True if adjacent solid blocks must still render their shared face */
  transparent: boolean;
  /** True if rendered in translucent pass (water) */
  liquid: boolean;
  /** True if player can break it */
  breakable: boolean;
  /** Base seconds to break by hand */
  hardness: number;
  /** Preferred tool category that speeds up mining */
  preferredTool: ToolCategory;
  /** Minimum tool tier required to harvest item drops & mine at full speed */
  minToolTier: number;
  /** Emitted block light level (0..15) */
  lightEmission: number;
  /** Extra skylight attenuation when passing through */
  lightOpacity: number;
  /** Render geometry style */
  shape: BlockRenderShape;
  /** Tile indices per face: [px, nx, py, ny, pz, nz] */
  faces: [TileIndex, TileIndex, TileIndex, TileIndex, TileIndex, TileIndex];
}

function allFaces(t: TileIndex): [TileIndex, TileIndex, TileIndex, TileIndex, TileIndex, TileIndex] {
  return [t, t, t, t, t, t];
}

