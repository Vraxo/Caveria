export function isBlockSolid(id: BlockId): boolean {
  return BLOCKS[id]?.solid ?? false;
}

export function isBlockOpaque(id: BlockId): boolean {
  const def = BLOCKS[id];
  return def ? def.solid && !def.transparent && def.shape === 'cube' : false;
}
